/**
 * Generates src/db/fold-table.ts: how SQLite's FTS5 trigram tokenizer with
 * remove_diacritics 1 folds each code point, read from SQLite itself rather
 * than reimplemented, so the short-query scan and hybrid query words (which
 * match in JavaScript) fold exactly like the trigram index they stand beside.
 * Run `npm run build` first; rerun when the bundled SQLite changes, and
 * test/db-search.test.mjs says so when the table drifts from the running one.
 *
 *   node scripts/gen-fold-table.mjs
 */
import { writeFileSync } from "node:fs";

import { foldTableFromSqlite } from "../dist/db/fold-probe.js";

const pairs = foldTableFromSqlite(0x20, 0x20000);
// Runs of consecutive code points shifted by the same delta, or every other
// code point shifted by the same delta (the alternating upper/lower blocks).
const runs = [];
for (const [cp, folded] of pairs) {
  const delta = folded - cp;
  const last = runs[runs.length - 1];
  if (last !== undefined && last[2] === delta) {
    const step = last[3];
    const next = last[0] + last[1] * step;
    if (last[1] === 1 && (cp === last[0] + 1 || cp === last[0] + 2)) {
      last[3] = cp - last[0];
      last[1] = 2;
      continue;
    }
    if (cp === next) {
      last[1] += 1;
      continue;
    }
  }
  runs.push([cp, 1, delta, 1]);
}

const body = runs.map((run) => `[${run.join(",")}]`).join(",");
writeFileSync(
  new URL("../src/db/fold-table.ts", import.meta.url),
  `/**
 * Generated by scripts/gen-fold-table.mjs from SQLite ${pairs.sqliteVersion}: every code point the FTS5
 * trigram tokenizer with remove_diacritics 1 folds to another, as runs of
 * [first code point, count, delta, step]. Do not edit by hand.
 */
export const FOLD_RUNS: ReadonlyArray<readonly [number, number, number, number]> = [${body}];
`
);
console.log(`${pairs.length} folded code points in ${runs.length} runs, SQLite ${pairs.sqliteVersion}`);
